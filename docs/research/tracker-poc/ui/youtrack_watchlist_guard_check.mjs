import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const source = readFileSync(new URL('./youtrack.jsx', import.meta.url), 'utf8');
assert.match(source, /ref=\{addFilmTitleRef\}/, 'the Add film title input must be focusable from the watchlist');
const prepare = source.match(/onPrepare=\{\(entry\) => (\{[^\n]+\})\}/)?.[1];
const select = source.match(/onSelect=\{\(item\) => (\{[^\n]+\})\}/)?.[1];
assert(prepare && select, 'watchlist callbacks must be present');
const state = {current:{busy:false,newTitle:'',newTmdbId:''}};
const projectRef = {current:'FILMPOC'};
let selected = null;
let focusCount = 0, notice = '';
const addFilmTitleRef = {current:{focus() { focusCount++; }}};
const setNotice = value => { notice = value; };
const draft = (title,id) => !!(title.trim() || id.trim());
const setTitle = value => {state.current.newTitle = value;};
const setId = value => {state.current.newTmdbId = value;};
const makePrepare = new Function('locked','guardsRef','createUncertain','projectRef','project','hasNewFilmDraft','setNewFilmTitle','setNewFilmTmdbId','addFilmTitleRef','setNotice', `return (entry) => ${prepare};`);
const makeSelect = new Function('locked','projectRef','project','selectFilm', `return (item) => ${select};`);
const run = makePrepare(false,state,false,projectRef,'FILMPOC',draft,setTitle,setId,addFilmTitleRef,setNotice);
run({tmdb_id:101,title:'Fictional A'});
assert.equal(focusCount,1,'preparing an unmatched film focuses its Add form');
assert.match(notice, /prepared.*add/i);
run({tmdb_id:102,title:'Fictional B'});
assert.deepEqual(state.current,{busy:false,newTitle:'Fictional A',newTmdbId:'101'},'a second click must not replace an unsaved draft');
assert.equal(focusCount,1,'a blocked second click must not change focus');
state.current.newTitle = ''; state.current.newTmdbId = '';
projectRef.current = 'FILMREAL';
run({tmdb_id:102,title:'Fictional B'});
assert.equal(state.current.newTitle,'','an old project handler must not prepare a draft');
const navigate = makeSelect(false,projectRef,'FILMPOC',id=>{selected=id;});
navigate({idReadable:'FILMPOC-1'});
assert.equal(selected,null,'an old project handler must not navigate');
projectRef.current='FILMPOC';
makeSelect(true,projectRef,'FILMPOC',id=>{selected=id;})({idReadable:'FILMPOC-1'});
assert.equal(selected,null,'a locked view must not navigate');
console.log('YouTrack Movary watchlist guards preserve drafts and project scope');
