import assert from "node:assert/strict";
import {filterFilms} from "./film_filters.js";
import {matchedLive} from "./kaneo_identity.js";
import {attachMatchedLive} from "./youtrack_tmdb.js";
import {filterYoutrackFilms} from "./youtrack_filters.js";

const kaneo = {id:"film-1",title:"Fictional Film",status:"to-do",fields:{"POC TMDB ID":"42","POC Source Director":"Fictional Source Director"}};
const youtrack = {id:"issue-1",idReadable:"FILMPOC-1",summary:"Fictional Film",customFields:[{name:"FilmIQ TMDB ID",value:42},{name:"FilmIQ Director",value:"Fictional Source Director"}]};
const data = {tmdb_id:42,title:"Fictional Film",directors:["Fictional Live Director"]};
const live = {data,requestedId:42};
const k = (query, record=kaneo) => filterFilms([record],{query,preferences:{}}).length;
const y = (query, record=youtrack) => filterYoutrackFilms([record],{query,preferences:{}}).length;
assert.equal(k("FILM"),1); assert.equal(y("FILM"),1);
assert.equal(k("SOURCE director"),1); assert.equal(y("SOURCE director"),1);
assert.equal(k("LIVE director"),0); assert.equal(y("LIVE director"),0);
assert.equal(k("LIVE director",{...kaneo,live:matchedLive(kaneo,live)}),1);
assert.equal(y("LIVE director",attachMatchedLive([youtrack],{"FILMPOC-1":live})[0]),1);
const mismatch = {data:{...data,title:"Different Work"},requestedId:42};
assert.equal(k("LIVE director",{...kaneo,live:matchedLive(kaneo,mismatch)}),0,"unmatched live metadata stays withheld");
assert.equal(y("LIVE director",attachMatchedLive([youtrack],{"FILMPOC-1":mismatch})[0]),0,"unmatched live metadata stays withheld");
assert.equal(k("unknown",{...kaneo,fields:{}}),0); assert.equal(y("unknown",{...youtrack,customFields:[]}),0);
assert.equal(filterFilms([kaneo],{query:"source director",watchlistOnly:true,preferences:{}}).length,0,"search does not bypass other filters");
assert.equal(filterYoutrackFilms([youtrack],{query:"source director",watchlistOnly:true,preferences:{}}).length,0);
console.log("Film search matches titles and loaded directors while respecting identity and other filters");
