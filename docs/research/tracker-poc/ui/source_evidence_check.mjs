import assert from "node:assert/strict";
import { evidenceExplanation, evidenceLabel, kaneoCardYear, sourceEvidenceLinks, sourceLabel, sourceYearLabel } from "./source_evidence.js";

assert.equal(evidenceLabel("critic_selection"), "Critic selection or ballot");
assert.equal(evidenceLabel("award_outcome"), "Award outcome");
assert.equal(evidenceLabel("registry_selection"), "Registry selection");
assert.equal(evidenceLabel("unknown"), "Evidence type unknown (source label: unknown)");
assert.equal(evidenceLabel(null), "Evidence type unknown");
assert.match(evidenceExplanation([{ kind: "critic_selection" }, { kind: "award_outcome" }]), /do not establish an individual film review/);
const unknownSource = { source_id: "Synthetic publisher", kind: "unrecognized" };
assert.equal(sourceLabel(unknownSource), "Synthetic publisher");
assert.equal(evidenceLabel(unknownSource.kind), "Evidence type unknown (source label: unrecognized)");
assert.equal(evidenceLabel("<script>"), "Evidence type unknown (source label: <script>)");
assert.match(evidenceExplanation([unknownSource]), /not established/);
assert.match(evidenceExplanation([]), /not established/);
const fictional = {tmdb_id:42,status:"available",links:[{source_id:"Fictional source",url:"https://example.invalid/film",entry_id:"entry",revision_id:"revision"}]};
assert.deepEqual(sourceEvidenceLinks(fictional,42), {status:"available",links:fictional.links});
assert.deepEqual(sourceEvidenceLinks(fictional,43), {status:"mismatch",links:[]});
assert.deepEqual(sourceEvidenceLinks(fictional,null), {status:"mismatch",links:[]});
assert.deepEqual(sourceEvidenceLinks({...fictional,tmdb_id:"42"},42), {status:"unknown",links:[]});
assert.deepEqual(sourceEvidenceLinks({...fictional,links:null},42), {status:"unknown",links:[]});
assert.deepEqual(sourceEvidenceLinks(null,42), {status:"unknown",links:[]});
assert.deepEqual(sourceEvidenceLinks({tmdb_id:42,status:"unknown",links:[]},42), {status:"unknown",links:[]});
const raw = JSON.stringify(fictional);
assert.equal(sourceYearLabel(raw, 42, "2001"), "Source-listed year 2001 (source field; verify identity and edits)");
assert.equal(sourceYearLabel(raw, 43, "2001"), null, "changed IDs must withhold the assertion");
assert.equal(sourceYearLabel(raw, null, "2001"), null);
assert.equal(sourceYearLabel("not JSON", 42, "2001"), null);
assert.equal(sourceYearLabel(JSON.stringify({...fictional, status:"unknown", links:[]}), 42, "2001"), null);
assert.equal(sourceYearLabel(JSON.stringify({...fictional, links:[]}), 42, "2001"), null);
assert.equal(sourceYearLabel(JSON.stringify({...fictional, links:[{}]}), 42, "2001"), null);
assert.equal(sourceYearLabel(JSON.stringify({...fictional, links:[fictional.links[0], "invalid"]}), 42, "2001"), null);
assert.equal(sourceYearLabel(JSON.stringify({...fictional, links:[{...fictional.links[0], url:"https://user:secret@example.invalid/film"}]}), 42, "2001"), null);
for (const year of ["", "0", "1799", "2201", "20x1", "2001.0", 2001, null]) assert.equal(sourceYearLabel(raw, 42, year), null);
const film = {fields:{"POC Evidence":raw, "POC Source Year":"2001"}};
assert.match(kaneoCardYear(film, 42), /Source-listed year 2001/);
assert.equal(kaneoCardYear({...film, live:{year:2002}}, 42), 2002, "available TMDB year keeps precedence");
assert.equal(kaneoCardYear({...film, fields:{...film.fields, "POC Year":"2003"}, live:{year:2002}}, 42), "2003", "stored release year keeps precedence");
assert.equal(kaneoCardYear(film, 43), "UNKNOWN YEAR", "changed identity withholds source year");
console.log("Evidence labels do not invent individual reviews");
